def generate_password_hash(password):
    """Hash de contraseña. scrypt (lo que usa Werkzeug por defecto) no existe en el Python de
    macOS, que va con LibreSSL: ahí crear o cambiar una contraseña fallaba. Se usa scrypt si está
    y, si no, PBKDF2-SHA256, que Werkzeug sigue verificando sin problema."""
    metodo = "scrypt" if hasattr(hashlib, "scrypt") else "pbkdf2:sha256:600000"
    return _generar_hash(password, method=metodo)

