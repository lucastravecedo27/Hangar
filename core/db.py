def a_sqlite(ddl):
    """Traduce el esquema (dialecto PostgreSQL) a SQLite."""
    import re
    ddl = re.sub(r"CREATE OR REPLACE FUNCTION.*?LANGUAGE sql[^;]*;", "", ddl, flags=re.S)
    ddl = ddl.replace(_ID, "INTEGER PRIMARY KEY AUTOINCREMENT")
    ddl = ddl.replace("to_char(CURRENT_DATE, 'YYYY-MM-DD')", "(date('now','localtime'))")
    ddl = ddl.replace("to_char(now(), 'YYYY-MM-DD HH24:MI:SS')", "(datetime('now','localtime'))")
    ddl = ddl.replace("TIMESTAMPTZ DEFAULT now()", "TEXT DEFAULT (datetime('now','localtime'))")
    ddl = ddl.replace("DEFAULT empresa_actual()", f"DEFAULT {EMPRESA_ESCRITORIO}")
    # FK compuesta (empresa_id, x) -> FK simple sobre x; «SET NULL (x)» -> «SET NULL».
    ddl = re.sub(r"FOREIGN KEY\(empresa_id, (\w+)\) REFERENCES (\w+)\(empresa_id, id\) ON DELETE SET NULL \(\w+\)",
                 r"FOREIGN KEY(\1) REFERENCES \2(id) ON DELETE SET NULL", ddl)
    ddl = re.sub(r"FOREIGN KEY\(empresa_id, (\w+)\) REFERENCES (\w+)\(empresa_id, id\)",
                 r"FOREIGN KEY(\1) REFERENCES \2(id)", ddl)
    return ddl


def conectar(empresa_id=None):
    """Conexión con la empresa fijada. `empresa_id=None` deja la conexión SIN empresa: las
    tablas de datos devuelven vacío y rechazan escrituras (es lo que ve la pantalla de acceso).
    `conectar(TODAS)` ve todas las empresas: sólo para migraciones y tareas de administración."""
    con = core_conexion.conectar()
    con.fijar_empresa(empresa_id)
    return con


def inicializar(sembrar=True):
    """Crea lo que falte del esquema y siembra los catálogos de piezas. Es idempotente."""
    con = conectar(TODAS)
    if ES_SQLITE:
        _inicializar_sqlite(con)
    else:
        # Varios procesos pueden arrancar a la vez (workers de Gunicorn en desarrollo, réplicas en
        # el servidor): el candado de sesión hace que migren de a uno; se suelta al cerrar `con`.
        con.execute("SELECT pg_advisory_lock(4826001)")
        con.commit()
        _inicializar_postgres(con)
    if sembrar:
        for clave in core_modelos.claves():
            _sembrar_catalogo(con, clave)
            _sembrar_despiece(con, clave)
        for clave in core_modelos.AVIONES:
            _sembrar_despiece_avion(con, clave)
        core_flota.sembrar_modelos(con, core_modelos.MODELOS, core_aeronaves.PLANTILLAS)
        # Piezas nuevas del catálogo DJI llegan también a los drones ya creados.
        for clave in core_modelos.claves():
            core_flota.completar_componentes(con, clave)
    core_flota.conciliar(con)
    con.commit()
    con.close()


def _inicializar_sqlite(con):
    con.executescript(a_sqlite(ESQUEMA))
    for tabla, columnas in COLUMNAS_FLOTA.items():
        _añadir_columnas(con, tabla, {k: a_sqlite(v) for k, v in columnas.items()})
    con.executescript(a_sqlite(ESQUEMA_FLOTA))
    for tabla, columnas in COLUMNAS_POSTERIORES.items():
        _añadir_columnas(con, tabla, {k: a_sqlite(v) for k, v in columnas.items()})
    for t in TABLAS_EMPRESA + TABLAS_MIXTAS:
        con.execute(f"CREATE INDEX IF NOT EXISTS ix_{t}_empresa ON {t}(empresa_id)")
    if not con.execute("SELECT 1 FROM empresas WHERE id=?", (EMPRESA_ESCRITORIO,)).fetchone():
        con.execute("INSERT INTO empresas(id, nombre) VALUES(?, 'Mi empresa')", (EMPRESA_ESCRITORIO,))
    con.commit()


def _inicializar_postgres(con):
    _migrar_multiempresa(con)
    con.executescript(ESQUEMA)
    # Columnas añadidas después de la primera versión (bases ya creadas no las traen).
    _añadir_columnas(con, "usuarios", {"nombre": "TEXT", "email": "TEXT",
                                       "rol": "TEXT NOT NULL DEFAULT 'admin'",
                                       "activo": "INTEGER NOT NULL DEFAULT 1", "ultimo_acceso": "TEXT",
                                       "empresa_id": "INTEGER REFERENCES empresas(id) ON DELETE CASCADE"})
    for tabla, columnas in COLUMNAS_FLOTA.items():
        _añadir_columnas(con, tabla, columnas)
    con.executescript(ESQUEMA_FLOTA)
    for tabla, columnas in COLUMNAS_POSTERIORES.items():
        _añadir_columnas(con, tabla, columnas)
    _arreglar_set_null(con)
    con.executescript(RLS)
    con.commit()


def _añadir_columnas(con, tabla, columnas):
    """ALTER TABLE idempotente para bases creadas antes de una versión."""
    for nombre, tipo in columnas.items():
        if ES_SQLITE:
            if _existe_tabla(con, tabla) and not _tiene_columna(con, tabla, nombre):
                # SQLite no admite añadir columnas con REFERENCES+DEFAULT no constante: se quita la FK.
                import re
                con.execute(f"ALTER TABLE {tabla} ADD COLUMN {nombre} {re.sub(r' REFERENCES .*$', '', tipo)}")
        else:
            con.execute(f"ALTER TABLE {tabla} ADD COLUMN IF NOT EXISTS {nombre} {tipo}")


def _existe_tabla(con, tabla):
    if ES_SQLITE:
        return bool(con.execute("SELECT 1 FROM sqlite_master WHERE type='table' AND name=?", (tabla,)).fetchone())
    return bool(con.execute("SELECT 1 FROM information_schema.tables WHERE table_name=?", (tabla,)).fetchone())


def _tiene_columna(con, tabla, columna):
    if ES_SQLITE:
        return any(f["name"] == columna for f in con.execute(f"PRAGMA table_info({tabla})").fetchall())
    return bool(con.execute("SELECT 1 FROM information_schema.columns WHERE table_name=? AND column_name=?",
                            (tabla, columna)).fetchone())


def _migrar_multiempresa(con):
    """Pasa una base de una sola empresa al esquema multi-empresa.

    Todo lo que ya existía pasa a ser de la empresa 1 («Empresa principal»). La clave primaria
    de `meta` y los códigos únicos de las órdenes pasan a ser únicos POR empresa.
    """
    if not _existe_tabla(con, "equipos") or _tiene_columna(con, "equipos", "empresa_id"):
        return
    con.executescript(ESQUEMA.split("CREATE TABLE IF NOT EXISTS meta(")[0])   # función + empresas
    if not con.execute("SELECT 1 FROM empresas").fetchone():
        con.execute("INSERT INTO empresas(id, nombre) VALUES(1, 'Empresa principal')")
        con.execute("SELECT setval(pg_get_serial_sequence('empresas','id'), 1)")
    for t in TABLAS_EMPRESA:
        if not _existe_tabla(con, t):
            continue
        con.execute(f"ALTER TABLE {t} ADD COLUMN IF NOT EXISTS empresa_id INTEGER")
        con.execute(f"UPDATE {t} SET empresa_id=1 WHERE empresa_id IS NULL")
        con.execute(f"ALTER TABLE {t} ALTER COLUMN empresa_id SET NOT NULL, "
                    f"ALTER COLUMN empresa_id SET DEFAULT empresa_actual()")
        con.execute(f"ALTER TABLE {t} ADD CONSTRAINT fk_{t}_empresa FOREIGN KEY(empresa_id) "
                    f"REFERENCES empresas(id) ON DELETE CASCADE")
    con.execute("ALTER TABLE meta DROP CONSTRAINT IF EXISTS meta_pkey")
    con.execute("ALTER TABLE meta ADD PRIMARY KEY(empresa_id, clave)")
    for t in ("ordenes_trabajo", "ordenes_servicio"):
        con.execute(f"ALTER TABLE {t} DROP CONSTRAINT IF EXISTS {t}_codigo_key")
        con.execute(f"ALTER TABLE {t} ADD CONSTRAINT {t}_empresa_codigo_key UNIQUE(empresa_id, codigo)")
    con.execute("ALTER TABLE usuarios ADD COLUMN IF NOT EXISTS empresa_id INTEGER REFERENCES empresas(id) ON DELETE CASCADE")
    con.execute("UPDATE usuarios SET empresa_id=1 WHERE empresa_id IS NULL")
    _reforzar_fks(con)
    con.commit()


# Claves foráneas COMPUESTAS (empresa_id, id): PostgreSQL no aplica RLS a las comprobaciones de
# clave foránea, así que sin esto una orden de una empresa podría apuntar a un dron de otra.
_FKS_COMPUESTAS = [
    # (tabla hija, columna, tabla padre, acción)
    ("registros", "equipo_id", "equipos", "SET NULL"),
    ("componentes", "equipo_id", "equipos", "CASCADE"),
    ("operaciones", "equipo_id", "equipos", "CASCADE"),
    ("mantenimientos", "equipo_id", "equipos", "CASCADE"),
    ("mantenimientos", "componente_id", "componentes", "SET NULL"),
    ("ordenes_trabajo", "equipo_id", "equipos", "CASCADE"),
    ("ot_tareas", "orden_id", "ordenes_trabajo", "CASCADE"),
    ("ot_tareas", "componente_id", "componentes", "SET NULL"),
    ("ordenes_servicio", "equipo_id", "equipos", "SET NULL"),
    ("os_productos", "orden_id", "ordenes_servicio", "CASCADE"),
    ("os_eventos", "orden_id", "ordenes_servicio", "CASCADE"),
]


def _reforzar_fks(con):
    for padre in ("equipos", "componentes", "ordenes_trabajo", "ordenes_servicio"):
        if not con.execute("SELECT 1 FROM pg_constraint WHERE conname=?", (f"{padre}_empresa_id_id_key",)).fetchone():
            con.execute(f"ALTER TABLE {padre} ADD CONSTRAINT {padre}_empresa_id_id_key UNIQUE(empresa_id, id)")
    for hija, col, padre, accion in _FKS_COMPUESTAS:
        con.execute(f"ALTER TABLE {hija} DROP CONSTRAINT IF EXISTS {hija}_{col}_fkey")
        nombre = f"{hija}_empresa_{col}_fkey"
        if not con.execute("SELECT 1 FROM pg_constraint WHERE conname=?", (nombre,)).fetchone():
            con.execute(f"ALTER TABLE {hija} ADD CONSTRAINT {nombre} FOREIGN KEY(empresa_id, {col}) "
                        f"REFERENCES {padre}(empresa_id, id) ON DELETE {accion}")
    _arreglar_set_null(con)


def _arreglar_set_null(con):
    """ON DELETE SET NULL sobre una clave compuesta (empresa_id, x) pone en nulo también
    empresa_id, que es NOT NULL: borrar un dron con órdenes o piezas fallaba. PostgreSQL 15+
    permite limitarlo a la columna de la referencia: SET NULL (x)."""
    filas = con.execute(
        """SELECT c.conname, c.conrelid::regclass::text tabla, pg_get_constraintdef(c.oid) d
           FROM pg_constraint c WHERE c.contype='f' AND pg_get_constraintdef(c.oid) LIKE '%(empresa_id, %ON DELETE SET NULL'""").fetchall()
    for f in filas:
        col = f["d"].split("(empresa_id, ", 1)[1].split(")", 1)[0]
        nuevo = f["d"] + f" ({col})"
        con.execute(f'ALTER TABLE {f["tabla"]} DROP CONSTRAINT {f["conname"]}')
        con.execute(f'ALTER TABLE {f["tabla"]} ADD CONSTRAINT {f["conname"]} {nuevo}')


def _sembrar_catalogo(con, modelo):
    """Vuelca las piezas con vida útil de un modelo (core/modelos.py).

    Las piezas que se retiran del catálogo (una carga de pago que la flota no monta, por ejemplo)
    se borran también de la base: si no, seguirían generando alertas de un equipo que no existe.
    La bitácora de reparaciones no se pierde — guarda el código y el nombre de la pieza aparte.
    """
    claves = [c[0] for c in core_modelos.catalogo(modelo)]
    if claves:
        marcas = ",".join("?" * len(claves))
        con.execute(f"DELETE FROM catalogo_piezas WHERE modelo=? AND clave NOT IN ({marcas})",
                    [modelo] + claves)
    for clave, modulo, nombre, vida_h, vida_m, nota, mesh in core_modelos.catalogo(modelo):
        con.execute(
            "INSERT INTO catalogo_piezas(modelo, clave, modulo, nombre, vida_util_horas, "
            "                            vida_util_meses, nota, mesh) VALUES(?,?,?,?,?,?,?,?) "
            "ON CONFLICT(modelo, clave) DO UPDATE SET "
            "modulo=excluded.modulo, nombre=excluded.nombre, "
            "vida_util_horas=excluded.vida_util_horas, vida_util_meses=excluded.vida_util_meses, "
            "nota=excluded.nota, mesh=excluded.mesh",
            (modelo, clave, modulo, nombre, vida_h, vida_m, nota, mesh),
        )
    con.commit()


# Las zonas viven en core/modelos.py, que es donde está todo lo que depende del modelo. Se
# reexportan aquí porque el resto del código las venía pidiendo a este módulo.
ZONA_DE_MODULO = core_modelos.ZONA_DE_MODULO_T50
ZONA_SUELTA = core_modelos.ZONA_SUELTA


def zonas_de_catalogo(modelo):
    """Zona de cada pieza con vida útil, deducida de la lámina en la que DJI la dibuja."""
    salida = dict(ZONA_SUELTA)
    for m in core_modelos.cargar_diagramas(modelo):
        for clave in m.get("piezas_catalogo") or []:
            # Una pieza puede salir en dos láminas (el motor está en los cuatro brazos); las
            # láminas hermanas caen en la misma zona, así que no hay ambigüedad que resolver.
            salida.setdefault(clave, m["zona"])
    return salida


def _sembrar_despiece(con, modelo):
    """Vuelca en la base el despiece de las láminas oficiales de un modelo.

    Los nombres en castellano vienen precalculados en el JSON con el mismo traductor que usa la
    pantalla de diagramas, para que una pieza se llame igual en el buscador, en la lámina y en
    la bitácora.
    """
    modulos = core_modelos.cargar_diagramas(modelo)
    # Las láminas que ya no existen (renombradas o retiradas del JSON) se van con sus piezas: si
    # no, el despiece del modelo arrastra para siempre las claves viejas.
    claves = [m["clave"] for m in modulos]
    if claves:
        marcas = ",".join("?" * len(claves))
        con.execute(f"DELETE FROM catalogo_despiece WHERE modelo=? AND modulo_clave NOT IN ({marcas})",
                    [modelo] + claves)
    for modulo in modulos:
        # Las variantes de un mismo número (lado, serie, equipo opcional: sólo en los aviones) se
        # buscan igual que la principal.
        filas = [v for p in modulo.get("partes") or []
                 for v in [p] + [dict(x, n=p["n"], auxiliar=p.get("auxiliar")) for x in p.get("variantes") or []]]
        for parte in filas:
            con.execute(
                "INSERT INTO catalogo_despiece(modelo, codigo, nombre, nombre_en, nombre_zh, "
                "                              modulo_clave, modulo, n, auxiliar) "
                "VALUES(?,?,?,?,?,?,?,?,?) "
                "ON CONFLICT(modelo, modulo_clave, n, codigo) DO UPDATE SET "
                "nombre=excluded.nombre, nombre_en=excluded.nombre_en, nombre_zh=excluded.nombre_zh, "
                "modulo=excluded.modulo, auxiliar=excluded.auxiliar",
                (modelo, parte.get("codigo") or "",
                 parte.get("nombre_es") or parte.get("nombre_en") or "",
                 parte.get("nombre_en"), parte.get("nombre_zh"), modulo.get("clave"),
                 modulo.get("nombre") or modulo.get("clave"), parte.get("n"),
                 1 if parte.get("auxiliar") else 0),
            )
        con.execute("UPDATE catalogo_despiece SET zona=? WHERE modelo=? AND modulo_clave=?",
                    (modulo["zona"], modelo, modulo["clave"]))
    for clave, zona in zonas_de_catalogo(modelo).items():
        con.execute("UPDATE catalogo_piezas SET zona=? WHERE modelo=? AND clave=?",
                    (zona, modelo, clave))
    # Cualquier pieza sin zona conocida se queda con su familia funcional, que es mejor que nada.
    con.execute("UPDATE catalogo_piezas SET zona=modulo WHERE zona IS NULL OR zona=''")
    con.commit()


def _sembrar_despiece_avion(con, clave):
    """El catálogo de un avión son miles de piezas: sólo se vuelca si la base no tiene ya las
    mismas láminas y el mismo número de piezas que su JSON."""
    modulos = core_modelos.cargar_diagramas(clave)
    esperado = (len(modulos), len({(m["clave"], p["n"], v.get("codigo") or "") for m in modulos
                                   for p in m.get("partes") or [] for v in [p] + (p.get("variantes") or [])}))
    fila = con.execute("SELECT COUNT(DISTINCT modulo_clave) l, COUNT(*) n FROM catalogo_despiece WHERE modelo=?",
                       (clave,)).fetchone()
    if modulos and (fila["l"], fila["n"]) != esperado:
        _sembrar_despiece(con, clave)


