def registrar_mantenimiento(con, equipo_id, componente_id, tipo, descripcion, costo, realizado_por,
                            fecha=None, motivo=None, orden_id=None, orden_codigo=None,
                            codigo_pieza=None, nombre_pieza=None, commit=True,
                            costo_repuesto=None, costo_mano_obra=None, firmado_por=None, licencia_firma=None,
                            reiniciar=True):
    """Anota la reparación en la bitácora y, si hubo cambio de pieza, la pone a cero DESDE LA
    FECHA DEL CAMBIO (antes se ponía a cero con fecha de hoy aunque el cambio fuera de otro día).

    Las horas que llevaba la pieza se calculan a esa fecha y se guardan: es el dato que dice si
    el cambio llegó por desgaste o adelantado por un daño. También se guarda cómo estaba el
    componente antes, para poder deshacer el cambio si el registro se borra.
    `costo` es el total; si llegan repuesto y mano de obra por separado, el total es su suma.
    """
    fecha = fecha or date.today().isoformat()
    if costo in (None, "") and (costo_repuesto is not None or costo_mano_obra is not None):
        costo = (costo_repuesto or 0) + (costo_mano_obra or 0)
    fila_eq = con.execute("SELECT horas_totales FROM equipos WHERE id=?", (equipo_id,)).fetchone()
    horas_actual = fila_eq["horas_totales"] if fila_eq else None
    pieza_id, horas_pieza = None, None
    antes = None
    if componente_id:
        comp = con.execute("SELECT pieza_id, horas_uso, uso_inicial, ciclos_inicial, fecha_ultimo_cambio, "
                           "fecha_instalado, pieza_serie_id FROM componentes WHERE id=?", (componente_id,)).fetchone()
        if comp:
            pieza_id = comp["pieza_id"]
            horas_pieza = core_flota.uso_hasta(con, componente_id, fecha)
            antes = comp
    cur = con.execute(
        "INSERT INTO mantenimientos(equipo_id, componente_id, tipo, fecha, horas_al_momento, descripcion, "
        "                           costo, realizado_por, pieza_id, horas_pieza, motivo, codigo_pieza, "
        "                           nombre_pieza, orden_id, orden_codigo, costo_repuesto, costo_mano_obra, "
        "                           firmado_por, licencia_firma, fecha_cambio_anterior, uso_inicial_anterior, "
        "                           ciclos_inicial_anterior, pieza_serie_id) "
        "VALUES(?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)",
        (equipo_id, componente_id, tipo, fecha, horas_actual, descripcion, costo, realizado_por,
         pieza_id, horas_pieza, motivo or ("desgaste" if componente_id else "otro"),
         codigo_pieza, nombre_pieza, orden_id, orden_codigo, costo_repuesto, costo_mano_obra,
         firmado_por, licencia_firma,
         (antes["fecha_ultimo_cambio"] or antes["fecha_instalado"]) if antes else None,
         antes["uso_inicial"] if antes else None, antes["ciclos_inicial"] if antes else None,
         antes["pieza_serie_id"] if antes else None),
    )
    if componente_id and antes and reiniciar:
        con.execute("UPDATE componentes SET uso_inicial=0, ciclos_inicial=0, fecha_ultimo_cambio=? WHERE id=?",
                    (fecha, componente_id))
        core_flota.recalcular_equipo(con, equipo_id)
    if commit:
        con.commit()
    return cur.lastrowid


def eliminar_mantenimiento(con, mantenimiento_id, usuario=None):
    """Borra un registro de la bitácora. Si ese registro fue el último cambio de la pieza, la
    pieza vuelve a como estaba antes (antes quedaba en cero horas aunque el cambio se anulara)."""
    m = con.execute("SELECT * FROM mantenimientos WHERE id=?", (mantenimiento_id,)).fetchone()
    if not m:
        return False
    if m["componente_id"] and m["uso_inicial_anterior"] is not None:
        comp = con.execute("SELECT fecha_ultimo_cambio FROM componentes WHERE id=?", (m["componente_id"],)).fetchone()
        otro_posterior = con.execute(
            "SELECT 1 FROM mantenimientos WHERE componente_id=? AND id<>? AND (fecha > ? OR (fecha = ? AND id > ?))",
            (m["componente_id"], m["id"], m["fecha"], m["fecha"], m["id"])).fetchone()
        if comp and comp["fecha_ultimo_cambio"] == m["fecha"] and not otro_posterior:
            con.execute("UPDATE componentes SET uso_inicial=?, ciclos_inicial=?, fecha_ultimo_cambio=? WHERE id=?",
                        (m["uso_inicial_anterior"], m["ciclos_inicial_anterior"] or 0,
                         m["fecha_cambio_anterior"], m["componente_id"]))
            # Si el anterior era la fecha de instalación, no hubo cambio previo.
            con.execute("UPDATE componentes SET fecha_ultimo_cambio=NULL WHERE id=? AND fecha_ultimo_cambio=fecha_instalado",
                        (m["componente_id"],))
    core_flota.auditar(con, "mantenimientos", mantenimiento_id, "eliminado", m["descripcion"] or m["nombre_pieza"],
                       None, usuario, "Registro de bitácora borrado")
    con.execute("DELETE FROM mantenimientos WHERE id=?", (mantenimiento_id,))
    core_flota.recalcular_equipo(con, m["equipo_id"])
    con.commit()
    return True


