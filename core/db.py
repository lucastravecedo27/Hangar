def series_plataforma(con, semanas=12):
    """Tendencia de las últimas `semanas` para el panel: acumulado de empresas, usuarios y
    drones existentes al cierre de cada semana, y operaciones registradas en cada semana.
    Devuelve listas de `semanas` valores (la última posición es la semana actual) y las
    variaciones de los últimos 30 días frente a los 30 anteriores."""
    dias = lambda col: core_conexion.sql_dias(col, core_conexion.sql_hoy())   # días desde col hasta hoy

    def acumulado(tabla, filtro=""):
        # Altas por semana (semanas ISO relativas a hoy) más lo que ya existía antes del rango.
        filas = con.execute(f"""
            SELECT LEAST({semanas - 1}, GREATEST(-1,
                     {semanas - 1} - ({dias('creado')} / 7))) AS semana,
                   COUNT(*) n
            FROM {tabla} WHERE creado IS NOT NULL {filtro}
            GROUP BY 1""").fetchall()
        por_semana = {int(f["semana"]): int(f["n"]) for f in filas}
        total, serie = por_semana.get(-1, 0), []
        for i in range(semanas):
            total += por_semana.get(i, 0)
            serie.append(total)
        return serie

    def altas_30d(tabla, filtro=""):
        f = con.execute(f"""
            SELECT COUNT(*) FILTER (WHERE {dias('creado')} <= 30) reciente,
                   COUNT(*) FILTER (WHERE {dias('creado')} <= 60 AND {dias('creado')} > 30) anterior
            FROM {tabla} WHERE creado IS NOT NULL {filtro}""").fetchone()
        return {"reciente": int(f["reciente"] or 0), "anterior": int(f["anterior"] or 0)}

    ops = con.execute(f"""
        SELECT {semanas - 1} - ({dias('fecha')} / 7) AS semana, COUNT(*) n
        FROM operaciones
        WHERE fecha >= to_char(CURRENT_DATE - {semanas * 7 - 1}, 'YYYY-MM-DD')
        GROUP BY 1""").fetchall()
    por_semana = {int(f["semana"]): int(f["n"]) for f in ops}
    ops_30 = con.execute(f"""
        SELECT COUNT(*) FILTER (WHERE {dias('fecha')} <= 30) reciente,
               COUNT(*) FILTER (WHERE {dias('fecha')} <= 60 AND {dias('fecha')} > 30) anterior
        FROM operaciones WHERE fecha >= to_char(CURRENT_DATE - 60, 'YYYY-MM-DD')""").fetchone()
    return {
        "empresas": {"serie": acumulado("empresas", "AND activa=1"), **altas_30d("empresas", "AND activa=1")},
        "usuarios": {"serie": acumulado("usuarios", "AND rol!='superadmin'"), **altas_30d("usuarios", "AND rol!='superadmin'")},
        "equipos": {"serie": acumulado("equipos", "AND estado!='baja'"), **altas_30d("equipos", "AND estado!='baja'")},
        "operaciones": {"serie": [por_semana.get(i, 0) for i in range(semanas)],
                        "reciente": int(ops_30["reciente"] or 0), "anterior": int(ops_30["anterior"] or 0)},
    }


