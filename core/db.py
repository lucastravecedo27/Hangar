def _variantes(token):
    """Formas alternativas de un término de búsqueda, incluida la propia."""
    formas = SINONIMOS.get(token)
    if formas:
        return [_normalizar(f) for f in formas]
    # Sin sinónimo propio, se prueba también sin la «s» final: «tornillos» -> «tornillo».
    if len(token) > 3 and token.endswith("s") and SINONIMOS.get(token[:-1]):
        return [_normalizar(f) for f in SINONIMOS[token[:-1]]]
    return [token]


def buscar_piezas(con, equipo_id, texto, limite=25, incluir_despiece=True):
    """Busca en TODO lo que se puede cambiar de un dron, en dos catálogos a la vez:

    - `seguimiento`: las piezas con vida útil (catalogo_piezas). Traen el componente concreto de
      ese dron, sus horas y su nivel de desgaste; cambiarlas reinicia el contador.
    - `despiece`: el despiece completo de los diagramas DJI (catalogo_despiece). Traen código de
      pieza y módulo, pero DJI no les da vida útil, así que no hay contador que reiniciar; se
      apuntan en la bitácora con su código y, si hace falta, se elige a mano qué pieza con horas
      del mismo módulo se reinicia.

    Se busca por nombre (castellano e inglés), módulo, clave y código, sin tildes y por trozos:
    «emp hel» encuentra «Empaque de hélice» y «l00870» encuentra el tornillo por su código.
    """
    from core import alertas as core_alertas
    # Cada término se expande a sus sinónimos: basta con que UNA de las formas aparezca.
    consulta = [_variantes(t) for t in _normalizar(texto).split()]
    def casa(*campos):
        heno = _normalizar(" ".join(str(c or "") for c in campos))
        return all(any(f in heno for f in formas) for formas in consulta)

    seguimiento = []
    for c in core_alertas.componentes_con_estado(con, equipo_id):
        # Se busca también por la familia funcional: quien teclea «propulsión» sigue encontrando
        # las hélices aunque la etiqueta que se muestre sea ya la zona.
        if consulta and not casa(c["nombre"], c["zona"], c["modulo"], c["clave"]):
            continue
        seguimiento.append({
            "tipo": "seguimiento",
            "componente_id": c["id"], "equipo_id": c["equipo_id"], "pieza_id": c["pieza_id"],
            "clave": c["clave"], "codigo": None, "nombre": c["nombre"],
            "modulo": c["zona"] or c["modulo"], "familia": c["modulo"],
            "modulo_clave": None, "nombre_en": None,
            "vida_util_horas": c["vida_util_horas"], "horas_uso": c["horas_uso"],
            "vida_util_meses": c["vida_util_meses"], "meses_en_servicio": c["meses_en_servicio"],
            "meses_restantes": c["meses_restantes"], "sin_plazo": c["sin_plazo"],
            "restante": c["restante"], "pct": c["pct"], "nivel": c["nivel"], "nota": c["nota"],
            "fecha_ultimo_cambio": c["fecha_ultimo_cambio"], "piezas_modulo": [],
        })
    # Lo más gastado primero: si alguien escribe «motor» normalmente busca el que toca cambiar.
    seguimiento.sort(key=lambda d: (-d["pct"], _normalizar(d["nombre"])))
    if not incluir_despiece:
        return seguimiento[:limite]

    # Qué piezas con horas cuelgan de cada módulo del despiece, ya resueltas al componente de
    # este dron: es lo que se ofrece para reiniciar cuando se cambia un recambio suelto.
    modelo = modelo_de_laminas(con, modelo_de_equipo(con, equipo_id))
    por_modulo = piezas_catalogo_por_modulo(modelo)
    comps = {c["clave"]: c for c in core_alertas.componentes_con_estado(con, equipo_id)}
    def piezas_del_modulo(modulo_clave):
        salida = []
        for clave in por_modulo.get(modulo_clave, []):
            c = comps.get(clave)
            if c:
                salida.append({"componente_id": c["id"], "nombre": c["nombre"], "clave": c["clave"],
                               "modulo": c["zona"] or c["modulo"],
                               "horas_uso": c["horas_uso"], "vida_util_horas": c["vida_util_horas"],
                               "vida_util_meses": c["vida_util_meses"],
                               "meses_en_servicio": c["meses_en_servicio"],
                               "meses_restantes": c["meses_restantes"], "pct": c["pct"],
                               "nivel": c["nivel"]})
        return salida

    despiece = []
    for f in con.execute("SELECT * FROM catalogo_despiece WHERE modelo=? ORDER BY modulo, n",
                         (modelo,)).fetchall():
        if consulta and not casa(f["nombre"], f["nombre_en"], f["zona"], f["modulo"], f["codigo"]):
            continue
        despiece.append({
            "tipo": "despiece",
            "componente_id": None, "equipo_id": equipo_id, "pieza_id": None,
            "clave": None, "codigo": f["codigo"], "nombre": f["nombre"],
            "modulo": f["zona"] or f["modulo"], "lamina": f["modulo"],
            "modulo_clave": f["modulo_clave"], "nombre_en": f["nombre_en"], "n": f["n"],
            "auxiliar": bool(f["auxiliar"]),
            "vida_util_horas": None, "horas_uso": None, "restante": None, "pct": None,
            "vida_util_meses": None, "meses_en_servicio": None, "meses_restantes": None,
            "sin_plazo": True, "nivel": None, "nota": None, "fecha_ultimo_cambio": None,
            "piezas_modulo": piezas_del_modulo(f["modulo_clave"]),
        })
    # Las principales antes que la tornillería auxiliar, y dentro de cada grupo por nombre.
    despiece.sort(key=lambda d: (d["auxiliar"], _normalizar(d["modulo"]), _normalizar(d["nombre"])))

    # Las piezas con horas van primero: son las que el mantenimiento mira todos los días.
    return (seguimiento + despiece)[:limite]


def modelo_de_laminas(con, modelo):
    """Modelo cuyas láminas y despiece valen para `modelo`: el propio, o la plantilla de la que
    sale (el Cessna de una empresa es una copia de la plantilla C188A y usa su catálogo)."""
    fila = con.execute("SELECT plantilla FROM modelos_activo WHERE clave=?", (modelo,)).fetchone()
    return core_modelos.con_laminas(modelo, fila["plantilla"] if fila else None) or modelo


def modelo_de_equipo(con, equipo_id):
    """Modelo de un equipo (dron o avión). Sin equipo concreto manda el predeterminado."""
    if equipo_id:
        fila = con.execute("SELECT modelo FROM equipos WHERE id=?", (equipo_id,)).fetchone()
        if fila and fila["modelo"]:
            return fila["modelo"]
    return core_modelos.PREDETERMINADO


def contar_piezas(con, modelo=None):
    """Cuántas piezas hay en cada catálogo. Lo usa la interfaz para decirlo en el buscador."""
    filtro, params = ("WHERE modelo=?", (modelo,)) if modelo else ("", ())
    uno = lambda sql: con.execute(sql, params).fetchone()["n"]
    return {
        "modelo": modelo,
        "seguimiento": uno(f"SELECT COUNT(*) n FROM catalogo_piezas {filtro}"),
        "despiece": uno(f"SELECT COUNT(*) n FROM catalogo_despiece {filtro}"),
        "modulos": uno(f"SELECT COUNT(DISTINCT modulo_clave) n FROM catalogo_despiece {filtro}"),
    }


# ---------- Bitácora de reparaciones ----------

def bitacora(con, equipo_id=None, desde=None, hasta=None, motivo=None, solo_piezas=False, limite=500):
    """Historial de reparaciones, una fila por intervención, con la pieza y sus horas al cambiar."""
    cond, params = ["1=1"], []
    if equipo_id:
        cond.append("m.equipo_id=?"); params.append(equipo_id)
    if desde:
        cond.append("m.fecha >= ?"); params.append(desde)
    if hasta:
        cond.append("m.fecha <= ?"); params.append(hasta)
    if motivo:
        cond.append("COALESCE(m.motivo,'desgaste') = ?"); params.append(motivo)
    if solo_piezas:
        cond.append("m.pieza_id IS NOT NULL")
    params.append(limite)
    filas = con.execute(
        f"""SELECT m.*, e.nombre AS equipo, e.modelo,
                   COALESCE(p.nombre, pc.nombre, m.nombre_pieza) AS pieza,
                   COALESCE(p.zona, pc.zona,
                            (SELECT cd.zona FROM catalogo_despiece cd WHERE cd.codigo = m.codigo_pieza LIMIT 1),
                            p.modulo, pc.modulo) AS modulo,
                   COALESCE(p.vida_util_horas, pc.vida_util_horas) AS vida_util_horas
            FROM mantenimientos m
            JOIN equipos e ON e.id = m.equipo_id
            LEFT JOIN catalogo_piezas p ON p.id = m.pieza_id
            LEFT JOIN componentes c ON c.id = m.componente_id
            LEFT JOIN catalogo_piezas pc ON pc.id = c.pieza_id
            WHERE {' AND '.join(cond)}
            ORDER BY m.fecha DESC, m.id DESC LIMIT ?""", params).fetchall()
    salida = []
    for f in filas:
        d = dict(f)
        d["motivo"] = d.get("motivo") or ("desgaste" if d.get("pieza_id") else "otro")
        d["motivo_txt"] = MOTIVOS.get(d["motivo"], d["motivo"])
        vida = d.get("vida_util_horas") or 0
        horas = d.get("horas_pieza")
        # Adelantado = la pieza se cambió sin haber consumido ni el 75 % de su vida útil.
        d["pct_vida"] = round(horas / vida * 100, 1) if vida and horas is not None else None
        d["adelantado"] = bool(d["pct_vida"] is not None and d["pct_vida"] < 75)
        salida.append(d)
    return salida


def resumen_bitacora(con, equipo_id=None):
    filas = bitacora(con, equipo_id, limite=10 ** 6)
    piezas = [f for f in filas if f["pieza_id"]]
    return {
        "total": len(filas),
        "piezas_cambiadas": len(piezas),
        "por_dano": sum(1 for f in filas if f["motivo"] == "daño"),
        "adelantados": sum(1 for f in piezas if f["adelantado"]),
        "costo": round(sum(f["costo"] or 0 for f in filas), 2),
    }


