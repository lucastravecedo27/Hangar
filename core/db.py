def crear_equipo(con, nombre, modelo, numero_serie, nota=None, tipo_activo=None, matricula=None,
                 anio=None, base=None, fabricante=None, contadores=None, fecha_alta=None):
    """Da de alta un activo (dron o avión) con los componentes de SU modelo y sus contadores.

    Para un avión se pasan las lecturas actuales (`contadores={'hobbs': 1204.6, 'tach': …}`):
    son el punto de partida, y las operaciones suman desde ahí."""
    m = core_flota.modelo_activo(con, modelo)
    if m and m["es_plantilla"]:
        modelo = core_flota.asegurar_modelo_propio(con, modelo)
        m = core_flota.modelo_activo(con, modelo)
    tipo = tipo_activo or (m["tipo_activo"] if m else "dron")
    cur = con.execute(
        "INSERT INTO equipos(nombre, modelo, numero_serie, nota, tipo_activo, matricula, anio, base, fabricante, "
        "                    fecha_alta) VALUES(?,?,?,?,?,?,?,?,?, COALESCE(?, to_char(CURRENT_DATE,'YYYY-MM-DD')))",
        (nombre, modelo, numero_serie, nota, tipo, matricula or None, anio or None, base or None,
         fabricante or (m["fabricante"] if m else None), fecha_alta),
    )
    equipo_id = cur.lastrowid
    lista = (m["contadores"] if m else None) or core_flota.contadores_de_tipo(tipo)
    core_flota.asegurar_contadores(con, equipo_id, tipo, contadores or {}, lista=lista)
    # Cada equipo arranca con los componentes de SU modelo: un T100 no tiene las piezas del T50.
    piezas = con.execute("SELECT id FROM catalogo_piezas WHERE modelo=?", (modelo,)).fetchall()
    for p in piezas:
        con.execute(
            "INSERT INTO componentes(equipo_id, pieza_id, uso_inicial, ciclos_inicial, fecha_instalado) "
            "VALUES(?,?,0,0,(SELECT fecha_alta FROM equipos WHERE id=?)) ON CONFLICT DO NOTHING",
            (equipo_id, p["id"], equipo_id),
        )
    core_flota.recalcular_equipo(con, equipo_id)
    con.commit()
    return equipo_id


