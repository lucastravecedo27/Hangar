def registrar_operacion(con, equipo_id, horas_vuelo, fecha=None, commit=True, recalcular=True, **campos):
    """Anota la jornada y recalcula el uso de las piezas desde las operaciones.

    En un avión, si se dan Hobbs inicial y final y no las horas, las horas de vuelo son el
    avance del Hobbs (así los reportes de horas valen para toda la flota)."""
    if (horas_vuelo in (None, "", 0)) and campos.get("hobbs_fin") is not None and campos.get("hobbs_ini") is not None:
        horas_vuelo = round(float(campos["hobbs_fin"]) - float(campos["hobbs_ini"]), 2)
    valores = [campos.get(c) for c in COLUMNAS_OPERACION]
    cur = con.execute(
        f"INSERT INTO operaciones(equipo_id, fecha, horas_vuelo, {', '.join(COLUMNAS_OPERACION)}) "
        f"VALUES(?, COALESCE(?, date('now')), ?, {', '.join('?' * len(COLUMNAS_OPERACION))})",
        (equipo_id, fecha, horas_vuelo, *valores),
    )
    if recalcular:
        core_flota.recalcular_equipo(con, equipo_id)
    if commit:
        con.commit()
    return cur.lastrowid


def eliminar_operacion(con, operacion_id):
    """Borra la jornada y recalcula: sólo cambia el uso de las piezas que la volaron."""
    fila = con.execute("SELECT equipo_id FROM operaciones WHERE id=?", (operacion_id,)).fetchone()
    if not fila:
        return False
    con.execute("DELETE FROM operaciones WHERE id=?", (operacion_id,))
    core_flota.recalcular_equipo(con, fila["equipo_id"])
    con.commit()
    return True


