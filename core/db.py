def contactos(con, rol=None, incluir_inactivos=True):
    """Directorio completo, con el trabajo que tiene cada uno a cuestas."""
    cond, params = ["1=1"], []
    if rol:
        cond.append("p.rol=?"); params.append(rol)
    if not incluir_inactivos:
        cond.append("p.activo=1")
    # Los contadores se calculan UNA vez por tabla (agrupados por nombre) y se cruzan con el
    # directorio: con seis subconsultas correlacionadas por persona, 300 contactos sobre
    # 100.000 operaciones tardaban 9 segundos; así tarda decenas de milisegundos.
    filas = con.execute(
        f"""SELECT p.*,
                   COALESCE(ot.abiertas, 0) ot_abiertas, COALESCE(ot.total, 0) ot_total,
                   COALESCE(os.abiertas, 0) os_abiertas, COALESCE(os.total, 0) os_total,
                   COALESCE(op.vuelos, 0) vuelos, COALESCE(op.horas, 0) horas_vuelo
            FROM personal p
            LEFT JOIN (SELECT asignado_a nombre, COUNT(*) total,
                              COUNT(*) FILTER (WHERE estado NOT IN ('completada','cancelada')) abiertas
                       FROM ordenes_trabajo GROUP BY asignado_a) ot ON ot.nombre = p.nombre
            LEFT JOIN (SELECT piloto nombre, COUNT(*) total,
                              COUNT(*) FILTER (WHERE estado NOT IN ('finalizada','cancelada')) abiertas
                       FROM ordenes_servicio GROUP BY piloto) os ON os.nombre = p.nombre
            LEFT JOIN (SELECT piloto nombre, COUNT(*) vuelos, SUM(horas_vuelo) horas
                       FROM operaciones GROUP BY piloto) op ON op.nombre = p.nombre
            WHERE {' AND '.join(cond)}
            ORDER BY p.activo DESC, p.nombre""", params).fetchall()
    salida = []
    for f in filas:
        d = dict(f)
        d["rol_txt"] = ROLES.get(d["rol"], d["rol"])
        d["horas_vuelo"] = round(d["horas_vuelo"] or 0, 1)
        d["operativo"] = d["rol"] in ROLES_OPERATIVOS
        d["licencia_vencida"] = bool(d.get("licencia_vence") and d["licencia_vence"] < _hoy())
        salida.append(d)
    return salida


def _hoy():
    from datetime import date
    return date.today().isoformat()


def resumen_contactos(con):
    lista = contactos(con)
    por_rol = {}
    for c in lista:
        por_rol[c["rol"]] = por_rol.get(c["rol"], 0) + 1
    return {
        "total": len(lista),
        "activos": sum(1 for c in lista if c["activo"]),
        "operativos": sum(1 for c in lista if c["operativo"] and c["activo"]),
        "sin_correo": sum(1 for c in lista if c["activo"] and not c["email"]),
        "licencias_vencidas": sum(1 for c in lista if c["licencia_vencida"]),
        "por_rol": por_rol,
        "roles": ROLES,
    }


