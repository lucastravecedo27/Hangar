def siguiente_codigo(con, tabla, prefijo):
    """Devuelve un código correlativo por año, p. ej. OT-2026-014."""
    from datetime import date
    anio = date.today().year
    patron = f"{prefijo}-{anio}-%"
    fila = con.execute(f"SELECT codigo FROM {tabla} WHERE codigo LIKE ? ORDER BY codigo DESC LIMIT 1", (patron,)).fetchone()
    n = int(fila["codigo"].rsplit("-", 1)[1]) + 1 if fila else 1
    return f"{prefijo}-{anio}-{n:03d}"


